#!/usr/bin/env python3
"""
Converts the dry CC0 recordings of the showcase's reverb mode to 16-bit mono
48 kHz WAV and embeds them in ../../sound_assets_reverb.h (helpers from
make_sfx_assets.py: ffmpeg decode and resample, tail trim, fades, -1 dBFS).

    python make_reverb_assets.py <dir with the Freesound downloads>

Sources, licenses and edits are listed in sounds.txt.
"""

import os
import sys

import make_sfx_assets as sfx

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "..", "sound_assets_reverb.h")

# source file, output wav, C symbol, cut (start, length) in s or None, tail threshold,
# fade in/out ms, seconds of silence appended (the gap before the loop repeats), note
ASSETS = [
    ("813622__securesubset__footsteps-stone-rock-concrete-cement.wav", "rv_footsteps_48k.wav",
     "g_rv_footsteps_wav", None, 0.002, 0, 50, 0.6,
     "Footsteps - Stone, Rock, Concrete, Cement by SecureSubset (Freesound 813622), CC0. Foley-pit recording; "
     "quiet tail trimmed, 50 ms fade-out, 0.6 s of silence appended."),
    ("154399__semccab__hand-clap.wav", "rv_clap_48k.wav",
     "g_rv_clap_wav", None, 0.002, 0, 30, 1.0,
     "hand clap.wav by semccab (Freesound 154399), CC0. 24-bit to 16-bit; quiet tail trimmed, 1 s of silence appended."),
    ("165206__metaepitome__water-drop-sound.wav", "rv_drop_48k.wav",
     "g_rv_drop_wav", None, 0.0, 0, 10, 1.4,
     "Water Drop Sound.wav by metaepitome (Freesound 165206), CC0. Stereo 44.1 kHz to mono 48 kHz; "
     "1.4 s of silence appended (one drip every 1.65 s)."),
    ("97773__timcam__acoustic-guitar-with-non_standard-tuning-phrase-5.wav", "rv_guitar_48k.wav",
     "g_rv_guitar_wav", (0.0, 8.0), 0.0, 0, 400, 1.0,
     "acoustic guitar with non_standard tuning phrase 5.wav by timcam (Freesound 97773), CC0. Stereo 44.1 kHz to "
     "mono 48 kHz; the first 8 s with a 400 ms fade-out, 1 s of silence appended."),
]


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src_dir = sys.argv[1]
    lines = [
        "/* Generated by assets/sfx/make_reverb_assets.py - DO NOT EDIT */",
        "/* Dry recordings for the reverb mode, from Freesound, all CC0 (see assets/sfx/sounds.txt). */",
        "#ifndef SOUND_ASSETS_REVERB_H",
        "#define SOUND_ASSETS_REVERB_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for src, out, sym, cut, tail, fade_in, fade_out, gap, note in ASSETS:
        pcm = sfx.decode(os.path.join(src_dir, src), 1, cut)
        if tail > 0:
            sfx.trim_tail(pcm, 1, tail)
        if fade_in or fade_out:
            sfx.fade(pcm, 1, fade_in, fade_out)
        pcm.extend([0.0] * int(gap * sfx.RATE))
        wav = sfx.to_wav16(pcm, 1)
        with open(os.path.join(HERE, out), "wb") as f:
            f.write(wav)
        print("%-22s %6.2f s %8d bytes" % (out, len(pcm) / sfx.RATE, len(wav)))

        lines.append("/* %s (%d bytes, channels=1, 48kHz PCM16)" % (out, len(wav)))
        lines.append(" * %s */" % note)
        lines.append("static const uint8_t %s[%d] = {" % (sym, len(wav)))
        for i in range(0, len(wav), 16):
            chunk = wav[i:i + 16]
            tail_comma = "," if i + 16 < len(wav) else ""
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + tail_comma)
        lines.append("};")
        lines.append("")
    lines.append("#endif /* SOUND_ASSETS_REVERB_H */")
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
